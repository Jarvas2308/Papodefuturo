create function public.upsert_market_exchange_rates_v1(records jsonb)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_record_count integer;
  v_item jsonb;
  v_key_count integer;
  v_upserted_count integer;
begin
  if records is null or pg_catalog.jsonb_typeof(records) <> 'array' then
    raise exception using
      errcode = '22023',
      message = 'market exchange rates batch must be an array';
  end if;

  v_record_count := pg_catalog.jsonb_array_length(records);
  if v_record_count > 100 then
    raise exception using
      errcode = '22023',
      message = 'market exchange rates batch exceeds 100 records';
  end if;

  if v_record_count = 0 then
    return pg_catalog.jsonb_build_object('attempted', 0, 'upserted', 0);
  end if;

  for v_item in
    select value
    from pg_catalog.jsonb_array_elements(records)
  loop
    if pg_catalog.jsonb_typeof(v_item) <> 'object' then
      raise exception using
        errcode = '22023',
        message = 'market exchange rate record must be an object';
    end if;

    if v_item ? 'id' or v_item ? 'created_at' then
      raise exception using
        errcode = '22023',
        message = 'market exchange rate record must not set id or created_at';
    end if;

    select pg_catalog.count(*)
    into v_key_count
    from pg_catalog.jsonb_object_keys(v_item);

    if v_key_count <> 6
      or not (
        v_item ? 'base_currency'
        and v_item ? 'quote_currency'
        and v_item ? 'rate_scaled'
        and v_item ? 'rate_scale'
        and v_item ? 'priced_at'
        and v_item ? 'source'
      )
    then
      raise exception using
        errcode = '22023',
        message = 'market exchange rate record has invalid fields';
    end if;
  end loop;

  -- Stable contract-specific key: market_exchange_rates.upsert.v1.
  perform pg_catalog.pg_advisory_xact_lock(4826317092550671822);

  insert into public.market_exchange_rates (
    base_currency,
    quote_currency,
    rate_scaled,
    rate_scale,
    priced_at,
    source
  )
  select
    populated.base_currency,
    populated.quote_currency,
    populated.rate_scaled,
    populated.rate_scale,
    populated.priced_at,
    populated.source
  from pg_catalog.jsonb_populate_recordset(
    null::public.market_exchange_rates,
    records
  ) as populated
  on conflict (base_currency, quote_currency, source, priced_at)
  do update set
    rate_scaled = excluded.rate_scaled,
    rate_scale = excluded.rate_scale;

  get diagnostics v_upserted_count = row_count;

  return pg_catalog.jsonb_build_object(
    'attempted', v_record_count,
    'upserted', v_upserted_count
  );
end;
$$;

comment on function public.upsert_market_exchange_rates_v1(jsonb) is
