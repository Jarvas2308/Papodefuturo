-- Tabela global de taxas de cambio (Sprint 5, DEC-052). Mesma motivacao de
-- market_asset_prices na migration anterior: exchange_rates
-- (20260713162000_create_exchange_rates.sql) e por usuario e nao pode ser
-- alimentada por um job agendado sem usuario. A tabela antiga permanece
-- intocada e em uso ate um ciclo futuro confirmar que nada mais depende dela.
--
-- Diferenca de produto explicita (DEC-052): a edicao manual de cambio
-- (saveManualUsdBrl, hoje exposta nas telas Dashboard/Carteira/Estrategia/
-- Aporte) e' removida junto desta migracao. Cambio global nao tem dono
-- individual para sobrescrever; o valor automatico via refresh-market-data ja
-- roda de verdade (DEC-043). Nenhuma RPC de escrita para authenticated existe
-- aqui de proposito.

create table public.market_exchange_rates (
  id bigint generated by default as identity primary key,
  base_currency text not null,
  quote_currency text not null,
  rate_scaled bigint not null,
  rate_scale integer not null default 1000000,
  priced_at timestamptz not null,
  source text not null,
  created_at timestamptz not null default now(),

  constraint market_exchange_rates_base_currency_check check (
    base_currency in ('BRL', 'USD')
  ),
  constraint market_exchange_rates_quote_currency_check check (
    quote_currency in ('BRL', 'USD')
  ),
  constraint market_exchange_rates_distinct_currency_check check (
    base_currency <> quote_currency
  ),
  constraint market_exchange_rates_rate_scaled_positive check (
    rate_scaled > 0
  ),
  constraint market_exchange_rates_rate_scale_check check (
    rate_scale = 1000000
  ),
  constraint market_exchange_rates_source_check check (
    source = 'market-provider'
  ),
  constraint market_exchange_rates_identity_unique unique (
    base_currency,
    quote_currency,
    source,
    priced_at
  )
);

create index market_exchange_rates_pair_priced_at_idx
on public.market_exchange_rates (base_currency, quote_currency, priced_at desc);

alter table public.market_exchange_rates enable row level security;

create policy "Authenticated users can read global market exchange rates"
on public.market_exchange_rates
for select
to authenticated
using (true);

revoke all on table public.market_exchange_rates from anon;
revoke all on table public.market_exchange_rates from authenticated;
grant select on table public.market_exchange_rates to authenticated;
grant select, insert, update, delete
on table public.market_exchange_rates
to service_role;

revoke all on sequence public.market_exchange_rates_id_seq from anon;
revoke all on sequence public.market_exchange_rates_id_seq from authenticated;
