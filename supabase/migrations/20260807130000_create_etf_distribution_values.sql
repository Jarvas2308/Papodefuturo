revoke all on function public.upsert_etf_distribution_values_v1(jsonb) from authenticated;
grant execute on function public.upsert_etf_distribution_values_v1(jsonb) to service_role;

revoke insert, update, delete, truncate
on table public.etf_distribution_values
from service_role;
